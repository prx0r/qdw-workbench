import {invoke} from '@tauri-apps/api/core';import type {NodeMetrics,HumanAction,Product,Factory} from './types';
export const api={
 config:()=>invoke<any>('load_config'),
 qdwGet:<T>(path:string)=>invoke<T>('qdw_get',{path}),
 qdwPost:<T>(path:string,body:unknown)=>invoke<T>('qdw_post',{path,body}),
 metrics:()=>invoke<NodeMetrics[]>('node_metrics'),
 nodePost:<T>(nodeId:string,path:string,body:unknown)=>invoke<T>('node_post',{nodeId,path,body}),
 acpOneShot:(command:string,args:string[],workspace:string,prompt:string)=>invoke<string>('acp_one_shot',{command,args,workspace,prompt}),
 gitState:(nodeId:string,workspace:string)=>invoke<any>('git_state',{nodeId,workspace}),
 files:(workspace:string)=>invoke<string[]>('list_files',{workspace}),
 read:(workspace:string,path:string)=>invoke<string>('read_text_file',{workspace,path}),
 write:(workspace:string,path:string,content:string)=>invoke<any>('write_text_file',{workspace,path,content}),
 pending:()=>invoke<HumanAction[]>('qdw_get',{path:'/v1/human/pending'}),
 products:()=>invoke<Product[]>('qdw_get',{path:'/v1/products'}),
 factories:()=>invoke<Factory[]>('qdw_get',{path:'/v1/factories'}),
 approve:(id:string,comment:string)=>invoke<any>('qdw_post',{path:`/v1/human/${id}/approve`,body:{actor_id:'workbench:human',decision:{comment}}}),
 decline:(id:string,comment:string)=>invoke<any>('qdw_post',{path:`/v1/human/${id}/decline`,body:{actor_id:'workbench:human',decision:{comment}}}),
 memoryRecent:(kind?:string,limit?:number)=>invoke<any[]>('memory_recent',{kind:kind||null,limit:limit||20}),
 memorySearch:(q:string,limit?:number)=>invoke<any[]>('memory_search',{q,limit:limit||10}),
 sessionList:()=>invoke<any[]>('session_list'),
 sessionCreate:(workspace:string,agentCommand?:string)=>invoke<any>('session_create',{workspace,agentCommand:agentCommand||null}),
 sessionPrompt:(sessionId:string,prompt:string)=>invoke<any>('session_prompt',{sessionId,prompt}),
 sessionClose:(sessionId:string)=>invoke<any>('session_close',{sessionId}),
 ptySpawn:(cwd:string,shell?:string,cols?:number,rows?:number)=>invoke<any>('pty_spawn',{cwd,shell:shell||null,cols:cols||null,rows:rows||null}),
 ptyWrite:(sessionId:string,data:string)=>invoke<any>('pty_write',{sessionId,data}),
 ptyRead:(sessionId:string)=>invoke<any>('pty_read',{sessionId}),
 ptyList:()=>invoke<any[]>('pty_list'),
 ptyClose:(sessionId:string)=>invoke<any>('pty_close',{sessionId}),
};
